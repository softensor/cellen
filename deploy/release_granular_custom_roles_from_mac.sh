#!/usr/bin/env bash
# Import, review through GitHub checks, merge, and deploy the granular Cellen role fix.
set -Eeuo pipefail

REPO_DIR=${CELLEN_REPO_DIR:-"$HOME/projects/cellen"}
BRANCH=fix/granular-custom-role-permissions
EXPECTED_SHA=066d08017e559fe1d673d84a27eb331245bf17ad
BUNDLE_FILE=$(mktemp "${TMPDIR:-/tmp}/cellen-granular-role.XXXXXX")
trap 'rm -f "$BUNDLE_FILE"' EXIT

if [[ $(uname -s) == Darwin ]]; then
  DECODE_FLAG=-D
else
  DECODE_FLAG=-d
fi
awk '/^# __CELLEN_BUNDLE__$/{copy=1; next} copy{sub(/^# /, ""); print}' "$0" \
  | base64 "$DECODE_FLAG" > "$BUNDLE_FILE"
git bundle verify "$BUNDLE_FILE"

cd "$REPO_DIR"
git switch master
git pull --ff-only origin master
git fetch "$BUNDLE_FILE" "+HEAD:refs/heads/$BRANCH"
git switch "$BRANCH"
[[ $(git rev-parse HEAD) == "$EXPECTED_SHA" ]] || {
  echo "Imported revision does not match $EXPECTED_SHA" >&2
  exit 2
}
bash deploy/release_independent_custom_roles_from_mac.sh
exit 0

