#!/usr/bin/env bash
# Self-contained importer and one-command production release.
# Run from the Cellen repository:
#   bash deploy/run_internal_payment_guardian_release.sh
set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
REPO_DIR=${CELLEN_REPO_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}
BRANCH=fix/internal-payments-by-guardian
EXPECTED_SHA=d91b193e33101ff6d17ca05c5fde1bf4962d36b2
BUNDLE_FILE=$(mktemp "${TMPDIR:-/tmp}/cellen-internal-payment-guardian.XXXXXX")
cleanup() { rm -f "$BUNDLE_FILE"; }
trap cleanup EXIT

if [[ $(uname -s) == Darwin ]]; then
  DECODE_FLAG=-D
else
  DECODE_FLAG=-d
fi
awk '/^# __CELLEN_BUNDLE__$/{copy=1; next} copy{sub(/^# /, ""); print}' "$0" \
  | base64 "$DECODE_FLAG" > "$BUNDLE_FILE"

cd "$REPO_DIR"
git switch master
git pull --ff-only origin master
git bundle verify "$BUNDLE_FILE"
git fetch "$BUNDLE_FILE" \
  "+refs/heads/$BRANCH:refs/heads/$BRANCH"
git switch "$BRANCH"
[[ $(git rev-parse HEAD) == "$EXPECTED_SHA" ]] || {
  echo "Imported revision does not match $EXPECTED_SHA" >&2
  exit 2
}
bash deploy/release_internal_payment_guardian_from_mac.sh
exit 0

