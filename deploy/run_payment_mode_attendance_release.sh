#!/usr/bin/env bash
# Self-contained importer and one-command production hotfix release.
# Run from the Cellen repository:
#   bash deploy/run_payment_mode_attendance_release.sh
set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
REPO_DIR=${CELLEN_REPO_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}
BRANCH=fix/payment-host-selector
EXPECTED_SHA=061f94b9f8619de7678cc609fe02d7bde63ea167
BUNDLE_FILE=$(mktemp "${TMPDIR:-/tmp}/cellen-payment-attendance.XXXXXX")
cleanup() { rm -f "$BUNDLE_FILE"; }
trap cleanup EXIT

if [[ $(uname -s) == Darwin ]]; then
  DECODE_FLAG=-D
else
  DECODE_FLAG=-d
fi
awk '/^# __CELLEN_BUNDLE__$/{copy=1; next} copy{sub(/^# /, ""); print}' "$0" \
  | base64 "$DECODE_FLAG" > "$BUNDLE_FILE"

cd "$REPO_DIR"
git switch master
git pull --ff-only origin master
git bundle verify "$BUNDLE_FILE"
git fetch "$BUNDLE_FILE" \
  "+refs/heads/$BRANCH:refs/heads/$BRANCH"
git switch "$BRANCH"
[[ $(git rev-parse HEAD) == "$EXPECTED_SHA" ]] || {
  echo "Imported revision does not match $EXPECTED_SHA" >&2
  exit 2
}
bash deploy/release_payment_attendance_hotfix_from_mac.sh
exit 0

