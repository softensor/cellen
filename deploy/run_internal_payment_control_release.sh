#!/usr/bin/env bash
# Self-contained importer and one-command release for Cellen internal payments.
# Run from the Cellen repository: bash deploy/run_internal_payment_control_release.sh
set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
REPO_DIR=${CELLEN_REPO_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}
BRANCH=feat/internal-payment-control
EXPECTED_SHA=4e7d8760b6926bf5d7fcecb5b07e6f1a728241b3
BUNDLE_FILE=$(mktemp "${TMPDIR:-/tmp}/cellen-internal-payments.XXXXXX")
cleanup() { rm -f "$BUNDLE_FILE"; }
trap cleanup EXIT

if [[ $(uname -s) == Darwin ]]; then
  DECODE_FLAG=-D
else
  DECODE_FLAG=-d
fi
awk '/^# __CELLEN_BUNDLE__$/{copy=1; next} copy{sub(/^# /, ""); print}' "$0" \
  | base64 "$DECODE_FLAG" > "$BUNDLE_FILE"
git bundle verify "$BUNDLE_FILE"

cd "$REPO_DIR"
git switch master
git pull --ff-only origin master
git fetch "$BUNDLE_FILE" "+HEAD:refs/heads/$BRANCH"
git switch "$BRANCH"
[[ $(git rev-parse HEAD) == "$EXPECTED_SHA" ]] || {
  echo "Imported revision does not match $EXPECTED_SHA" >&2
  exit 2
}
bash deploy/release_internal_payment_control_from_mac.sh
exit 0

